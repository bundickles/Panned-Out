// Run against the SCRUM-138 UI and SCRUM-136/137 backend. Uses isolated test accounts.
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
(async () => {
 const browser = await chromium.launch({ headless: true, ...(process.env.CHROME_PATH ? { executablePath: process.env.CHROME_PATH } : {}) });
 try {
  const page = await browser.newPage({viewport:{width:1440,height:900}});
  page.setDefaultTimeout(8000);
  const base = process.env.BASE_URL || 'http://127.0.0.1:5175';
  await page.route('https://fonts.googleapis.com/**', route => route.abort());
  await page.route('https://fonts.gstatic.com/**', route => route.abort());
  const account = await page.request.post(`${base}/api/auth/register`, {headers:{'X-Panned-Out-Request':'1'}, form:{email:`mealplans-${Date.now()}@example.test`,password:'isolated-mealplans-test-password'}});
  assert.equal(account.status(),201);
  const catalogResponse = await page.request.get(`${base}/api/recipes?filter=suggested`);
  assert.equal(catalogResponse.status(),200);
  const catalog = await catalogResponse.json();
  assert.ok(catalog.length>0,'Use a nonempty suggested catalog for the integration check');
  await page.goto(`${base}/meal-plans`);
  const browse=page.getByRole('region',{name:'Browse recipes',exact:true});
  await browse.getByRole('link').first().waitFor();
  assert.equal(await browse.getByRole('link').count(),catalog.length);
  if (process.env.SCREENSHOT_PATH) await page.screenshot({path:process.env.SCREENSHOT_PATH,fullPage:true});
  for(const plan of ['High Protein','Low Calorie','Keto','Balanced']) {
   await page.getByRole('button',{name:new RegExp(`${plan}.*Explore Plan`)}).click();
   const dialog=page.getByRole('dialog',{name:plan,exact:true});
   const expected=catalog.filter(recipe=>recipe.plan===plan);
   await dialog.getByRole('link').first().waitFor();
   assert.equal(await dialog.getByRole('link').count(),expected.length);
   await dialog.getByRole('link',{name:new RegExp(expected[0].name.replace(/[.*+?^${}()|[\]\\]/g,'\\$&'))}).click();
   await page.getByRole('heading',{name:expected[0].name,exact:true,level:1}).waitFor();
   await page.reload();
   await page.getByRole('heading',{name:expected[0].name,exact:true,level:1}).waitFor();
   await page.getByRole('button',{name:'Back to Meal Plans'}).click();
   await page.getByRole('dialog',{name:plan,exact:true}).waitFor();
   await page.getByRole('button',{name:'Close',exact:true}).click();
   await page.waitForURL(url=>!url.searchParams.has('plan'));
   await page.getByRole('dialog').waitFor({state:'hidden'});
  }
  console.log('PASS real catalog, all four plans, namespaced details, refresh and return-to-plan');
  await page.getByLabel('Recipe collection').selectOption('saved');
  await browse.getByText('No recipes are available for this filter yet.').waitFor();
  const saved=await page.request.post(`${base}/api/recipes`,{headers:{'X-Panned-Out-Request':'1'},form:{name:'Private integration recipe',category:'My Recipes',difficulty:'Easy',mealType:'Dinner',ingredients:'Rice',instructions:'Cook rice.',prepTime:'12'}});
  assert.equal(saved.status(),201);
  await page.reload();await browse.getByRole('link',{name:/Private integration recipe/}).waitFor();
  await page.getByLabel('Recipe collection').selectOption('all');
  await browse.getByRole('link',{name:/Private integration recipe/}).waitFor();
  await page.waitForTimeout(500);
  assert.equal(await browse.getByRole('link').count(),catalog.length+1);
  console.log('PASS saved empty state, private recipes and all filter');
  let fail=true;
  await page.route('**/api/recipes?filter=suggested',route=>fail ? route.fulfill({status:503,contentType:'application/json',body:JSON.stringify({error:'Temporary test outage'})}) : route.continue());
  await page.getByLabel('Recipe collection').selectOption('suggested');
  await page.getByRole('alert').getByText('Temporary test outage').waitFor();
  fail=false;await page.getByRole('button',{name:'Retry loading recipes'}).click();
  await browse.getByRole('link').first().waitFor();
  assert.equal(await browse.getByRole('link').count(),catalog.length);
  console.log('PASS server error and successful retry');
  await page.unroute('**/api/recipes?filter=suggested');
  await page.route('**/api/recipes?filter=suggested',route=>route.fulfill({status:200,contentType:'application/json',body:'[]'}));
  await page.reload();await browse.getByText('No recipes are available for this filter yet.').waitFor();
  await page.getByRole('button',{name:/Keto.*Explore Plan/}).click();
  await page.getByRole('dialog',{name:'Keto',exact:true}).getByText('No recipes are available for Keto yet.').waitFor();
  console.log('PASS empty catalog and empty plan');
  await page.unroute('**/api/recipes?filter=suggested');
  let release;const held=new Promise(resolve=>{release=resolve});
  await page.route('**/api/recipes?filter=suggested',async route=>{await held;await route.fulfill({status:200,contentType:'application/json',body:JSON.stringify(catalog)}).catch(()=>{});});
  await page.goto(`${base}/meal-plans`);
  await browse.getByText('Loading recipes…').waitFor();
  await page.getByLabel('Recipe collection').selectOption('saved');
  await browse.getByRole('link',{name:/Private integration recipe/}).waitFor();
  release();await page.waitForTimeout(200);
  assert.equal(await browse.getByRole('link').count(),1);
  console.log('PASS loading indicator and stale-response protection');
  await page.unroute('**/api/recipes?filter=suggested');
  await page.route('**/api/recipes?filter=suggested',route=>route.fulfill({status:401,contentType:'application/json',body:'{"error":"Sign in required"}'}));
  await page.getByLabel('Recipe collection').selectOption('suggested');
  await page.waitForURL('**/login');
  console.log('PASS expired-session redirect');
 } finally { await browser.close(); }
})().catch(error=>{console.error(error);process.exitCode=1;});
